# As published
# ---------------------------------------------------------------------------
class Relaxer:
    def __init__(self, schema):
        self.schema = schema
        self.log = collections.defaultdict(set)   # (location, change) -> record names
        self.reindex()

    def reindex(self):
        """Map each sub-schema object to its JSON pointer, for the log."""
        self.pointers = {}

        def walk(node, pointer):
            if isinstance(node, dict):
                self.pointers[id(node)] = pointer
                for key, value in node.items():
                    walk(value, f"{pointer}/{key}")
            elif isinstance(node, list):
                for i, value in enumerate(node):
                    walk(value, f"{pointer}/{i}")

        walk(self.schema, "")

    def relax(self, error, record, changes):
        """Queue the smallest change that removes this error. error.schema is
        the sub-schema holding the failed keyword, wherever a $ref led."""
        rule = error.validator
        owner = error.schema
        value = error.instance
        if rule in ("anyOf", "oneOf"):
            if not error.context:      # oneOf with more than one match
                self.queue(owner, "oneOf overlaps: oneOf -> anyOf", record, changes)
            else:
                self.relax_branch(error, record, changes)
        elif rule == "required":
            name = re.match(r"'(.+?)' is a required", error.message).group(1)
            self.queue(owner, f"not required: {name}", record, changes)
        elif rule == "type":
            self.queue(owner, f"type also {JSON_TYPES[type(value)]}", record, changes)
        elif rule == "enum":
            self.queue(owner, f"enum also {value!r}", record, changes)
        elif rule == "format":
            self.queue(owner, f"format dropped ({error.validator_value})", record, changes)
        elif rule == "not":
            self.queue(owner, "owl:cardinality one -> many: arrays allowed", record, changes)
        else:
            self.queue(owner, f"keyword dropped: {rule}", record, changes)

    def relax_branch(self, error, record, changes):
        """Fix the closest branch; if the value's type fits no branch, add one."""
        by_branch = collections.defaultdict(list)
        for child in error.context:
            by_branch[child.schema_path[0]].append(child)
        depth = len(error.absolute_path)

        def wrong_type(children):
            return any(c.validator == "type" and len(c.absolute_path) == depth for c in children)

        fitting = {b: c for b, c in by_branch.items() if not wrong_type(c)}
        if not fitting:
            kind = JSON_TYPES[type(error.instance)]
            self.queue(error.schema, f"new branch for {kind} values", record, changes)
            return
        branch = min(fitting, key=lambda b: (len(fitting[b]), str(b)))
        for child in fitting[branch]:
            self.relax(child, record, changes)

    def queue(self, node, change, record, changes):
        pointer = self.pointers[id(node)]
        self.log[(pointer, change)].add(record)
        changes[(pointer, change)] = (id(node), node)

    def apply(self, changes):
        for (_, change), (_, node) in changes.items():
            if change.startswith("not required: "):
                name = change.split(": ", 1)[1]
                node["required"] = [r for r in node.get("required", []) if r != name]
                recommended = node.setdefault("recommended", [])
                if name not in recommended:
                    recommended.append(name)
            elif change.startswith("type also "):
                kinds = node["type"] if isinstance(node["type"], list) else [node["type"]]
                node["type"] = kinds + [change.rsplit(" ", 1)[1]]
            elif change.startswith("enum also "):
                node["enum"].append(eval_value(change))
            elif change.startswith("format dropped"):
                node.pop("format", None)
            elif change.startswith("owl:cardinality one"):
                node.pop("not", None)
                node["owl:cardinality"] = "many"
            elif change.startswith("oneOf overlaps"):
                node["anyOf"] = node.pop("oneOf")
            elif change.startswith("new branch for "):
                kind = change.split()[3]
                key = "anyOf" if "anyOf" in node else "oneOf"
                node[key].append({"type": kind, "$comment": "observed in records"})
            elif change.startswith("keyword dropped: "):
                node.pop(change.split(": ", 1)[1], None)


def eval_value(change):
    return json.loads(json.dumps(eval(change.split("enum also ", 1)[1])))  # our own repr


def load_examples():
    return {p.name: json.loads(p.read_text(encoding="utf-8"))
            for p in sorted(EXAMPLES.glob("*.json")) if p.name != "INDEX.json"}


def as_published(specified, examples):
    schema = copy.deepcopy(specified)
    schema["title"] = "nde:Dataset, as published"
    schema["$comment"] = ("The as-specified schema relaxed against niaidExamples/; "
                          "relaxations.json logs each change. Evidence about those "
                          "records, not a specification.")
    relaxer = Relaxer(schema)
    for round_no in range(MAX_ROUNDS):
        validator = Draft7Validator(schema, format_checker=FormatChecker())
        changes = {}
        for name, record in examples.items():
            for error in validator.iter_errors(record):
                relaxer.relax(error, name, changes)
        if not changes:
            break
        relaxer.apply(changes)
        relaxer.reindex()
    else:
        raise RuntimeError(f"still failing after {MAX_ROUNDS} rounds")

    undeclared = collections.Counter(
        key for record in examples.values() for key in record
        if key not in schema["properties"] and not key.startswith("@"))
    for key, count in sorted(undeclared.items()):
        schema["properties"][key] = {"$comment": f"Not in NIAID's schema; in {count} of "
                                                 f"{len(examples)} example records."}
    Draft7Validator.check_schema(schema)
    log = [{"location": loc, "change": change, "records": len(recs), "examples": sorted(recs)[:5]}
           for (loc, change), recs in sorted(relaxer.log.items(), key=lambda kv: (-len(kv[1]), kv[0]))]
    return schema, log, dict(undeclared), round_no + 1


def nested_undeclared(schema, examples):
    """Names used anywhere in the records that the schema declares nowhere."""
    declared = set()

    def schema_names(node):
        if isinstance(node, dict):
            declared.update(node.get("properties", {}))
            for value in node.values():
                schema_names(value)
        elif isinstance(node, list):
            for value in node:
                schema_names(value)

    schema_names(schema)
    used = collections.Counter()

    def record_names(node):
        if isinstance(node, dict):
            used.update(k for k in node if not k.startswith("@"))
            for value in node.values():
                record_names(value)
        elif isinstance(node, list):
            for value in node:
                record_names(value)

    for record in examples.values():
        record_names(record)
    return {k: n for k, n in sorted(used.items()) if k not in declared}


def main():
    source = json.loads(SOURCE.read_text(encoding="utf-8"))
    classes = [n for n in source["@graph"] if n["@type"] == "rdfs:Class"]
    note = "NDE_schema.jsonld (nde-schemas b9abacc9a4f5)"

    cardinality_log = {}
    specified = {}
    for node in classes:
        name = node["@id"].split(":", 1)[1]
        schema, log = as_specified(node, note)
        write_json(OUT / "asSpecified" / f"{name}.schema.json", schema)
        specified[name] = schema
        cardinality_log[name] = log
        print(f"asSpecified/{name}: {len(schema['properties'])} properties, "
              f"{len(schema.get('required', []))} required, {len(log)} cardinality changes")

    examples = load_examples()
    base = Draft7Validator(specified["Dataset"])
    print(f"\n{len(examples)} examples; passing asSpecified/Dataset: "
          f"{sum(not list(base.iter_errors(r)) for r in examples.values())}")

    published, log, undeclared, rounds = as_published(specified["Dataset"], examples)
    write_json(OUT / "asPublished" / "Dataset.schema.json", published)
    write_json(OUT / "relaxations.json", {
        "note": "How asPublished/Dataset.schema.json differs from asSpecified/Dataset.schema.json, "
                "and which example records required each change. 'records' counts the records "
                "that failed the rule when it was relaxed; an earlier relaxation can hide later ones.",
        "relaxations": log,
        "undeclaredTopLevel": undeclared,
        "undeclaredNested": nested_undeclared(published, examples),
        "cardinalityChanges": cardinality_log,
    })
    check = Draft7Validator(published, format_checker=FormatChecker())
    print(f"asPublished/Dataset: {sum(not list(check.iter_errors(r)) for r in examples.values())} "
          f"of {len(examples)} pass, after {rounds} rounds and {len(log)} relaxations")


if __name__ == "__main__":
    main()
