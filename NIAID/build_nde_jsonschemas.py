#!/usr/bin/env python3
"""build_nde_jsonschemas.py - JSON Schemas for NIAID records, in two forms.

NIAID's schema (schemas/NDE_schema.jsonld) carries a draft-07 JSON Schema in the
$validation of each class node. Property names are bare, as the portal publishes
them.

  jsonschema/asSpecified/<Class>.schema.json
      $validation for each class, with owl:cardinality (an annotation validators
      ignore) made enforceable where the schema does not already say it: a "one"
      property that accepts arrays is refused them, and a "many" property that
      refuses arrays is given them. This is what NIAID says a record should be.

  jsonschema/asPublished/Dataset.schema.json
      The Dataset schema relaxed against the records in niaidExamples/, which do
      not satisfy it. Each failing record changes only the rule it broke, in the
      closest branch of any anyOf/oneOf, and jsonschema/relaxations.json logs every
      change with the records that needed it. Top-level names the schema does not
      declare are added, marked as undeclared. Dataset only, because the examples
      are all Datasets: the other classes have no evidence to relax against.

The relaxations are evidence about these records, not a specification: read
relaxations.json before treating a relaxed rule as intended.

Usage:
    python build_nde_jsonschemas.py
"""
import collections
import copy
import json
import re
from pathlib import Path

from jsonschema import Draft7Validator, FormatChecker

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "schemas" / "NDE_schema.jsonld"
EXAMPLES = HERE / "niaidExamples"
OUT = HERE / "jsonschema"
JSON_TYPES = {str: "string", bool: "boolean", int: "integer", float: "number",
              dict: "object", list: "array", type(None): "null"}
MAX_ROUNDS = 60


def write_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


# ---------------------------------------------------------------------------
# As specified
# ---------------------------------------------------------------------------
def accepts_array(node, root):
    """Can this schema node accept an array value?"""
    if "$ref" in node:
        return accepts_array(resolve_ref(root, node["$ref"]), root)
    branches = node.get("anyOf") or node.get("oneOf")
    if branches:
        return any(accepts_array(b, root) for b in branches)
    kind = node.get("type")
    if kind is None:
        return True
    return "array" in kind if isinstance(kind, list) else kind == "array"


def resolve_ref(root, ref):
    node = root
    for token in ref.lstrip("#/").split("/"):
        node = node[token]
    return node


def enforce_cardinality(node, root, path, log):
    """Make owl:cardinality effective on every node that states it."""
    if isinstance(node, list):
        for i, item in enumerate(node):
            enforce_cardinality(item, root, f"{path}/{i}", log)
        return
    if not isinstance(node, dict):
        return
    for key, value in list(node.items()):
        enforce_cardinality(value, root, f"{path}/{key}", log)
    card = node.get("owl:cardinality")
    if card == "one" and accepts_array(node, root):
        node["not"] = {"type": "array"}
        log.append({"location": path, "owl:cardinality": "one",
                    "change": "refuses arrays, which the schema otherwise accepted"})
    elif card == "many" and not accepts_array(node, root):
        single = {k: node.pop(k) for k in list(node)
                  if k not in ("description", "abstract", "owl:cardinality")}
        node["anyOf"] = [single, {"type": "array", "items": copy.deepcopy(single)}]
        log.append({"location": path, "owl:cardinality": "many",
                    "change": "accepts an array, which the schema otherwise refused"})


def as_specified(class_node, commit_note):
    schema = copy.deepcopy(class_node["$validation"])
    log = []
    enforce_cardinality(schema, schema, "", log)
    schema = {"title": f"{class_node['@id']}, as specified",
              "$comment": f"The $validation of {class_node['@id']} in {commit_note}, with "
                          "owl:cardinality made enforceable; generated by "
                          "build_nde_jsonschemas.py.",
              **schema}
    Draft7Validator.check_schema(schema)
    return schema, log


